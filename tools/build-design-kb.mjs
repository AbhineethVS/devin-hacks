// Builds extension/design-kb.js from the UI UX Pro Max data (MIT, github.com/nextlevelbuilder/ui-ux-pro-max-skill).
// usage: node build-design-kb.mjs <path to ui-ux-pro-max/data>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dataDir = process.argv[2];
if (!dataDir) throw new Error("Pass the ui-ux-pro-max data directory.");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((v) => v !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] || "").trim()])));
}

const read = (name) => parseCsv(fs.readFileSync(path.join(dataDir, `${name}.csv`), "utf8").replace(/^\uFEFF/, ""));
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1) + "…" : s);

const styles = read("styles")
  .filter((r) => !/deprecated|replaced/i.test(r.Status || ""))
  .map((r) => ({
    name: r["Style Category"],
    keys: `${r.Keywords} ${r["AI Prompt Keywords"]} ${r.Aliases || ""} ${r["Best For"]}`.toLowerCase(),
    text: [
      `STYLE: ${r["Style Category"]}: ${clip(r.Keywords, 220)}`,
      `colours: ${clip(r["Primary Colors"], 160)}; secondary ${clip(r["Secondary Colors"], 140)}`,
      `effects: ${clip(r["Effects & Animation"], 220)}`,
      `css: ${clip(r["CSS/Technical Keywords"], 260)}`,
      `best for: ${clip(r["Best For"], 140)}; avoid for: ${clip(r["Do Not Use For"], 140)}`,
    ].join("\n  "),
  }));

const fonts = read("typography").map((r) => ({
  name: r["Font Pairing Name"],
  keys: `${r["Mood/Style Keywords"]} ${r["Best For"]} ${r.Category}`.toLowerCase(),
  text: `FONTS: ${r["Font Pairing Name"]}: ${r["Heading Font"]} + ${r["Body Font"]} (${r["Mood/Style Keywords"]}). ${clip(r.Notes, 160)} ${r["CSS Import"]}`,
}));

const palettes = new Map(read("colors").map((r) => [r["Product Type"], r]));
const products = read("products").map((r) => {
  const p = palettes.get(r["Product Type"]);
  const palette = p ? `primary ${p.Primary}, secondary ${p.Secondary}, accent ${p.Accent}, background ${p.Background}, foreground ${p.Foreground}, muted ${p.Muted}, border ${p.Border}. ${clip(p.Notes, 120)}` : "";
  return {
    name: r["Product Type"],
    keys: `${r["Product Type"]} ${r.Keywords}`.toLowerCase(),
    text: [
      `PRODUCT TYPE: ${r["Product Type"]}: recommended ${r["Primary Style Recommendation"]} (also ${r["Secondary Styles"]}); page pattern ${r["Landing Page Pattern"]}`,
      `palette focus: ${r["Color Palette Focus"]}${palette ? `; reference palette: ${palette}` : ""}`,
      `considerations: ${clip(r["Key Considerations"], 200)}`,
    ].join("\n  "),
  };
});

const patterns = read("landing").map((r) => ({
  name: r["Pattern Name"],
  keys: `${r["Pattern Name"]} ${r.Keywords} ${r.Aliases || ""}`.toLowerCase(),
  text: `PAGE PATTERN: ${r["Pattern Name"]}: ${r["Section Order"]}. CTA: ${r["Primary CTA Placement"]}. ${clip(r["Color Strategy"], 160)}`,
}));

const ux = read("ux-guidelines")
  .filter((r) => /web|all/i.test(r.Platform) && /high|critical/i.test(r.Severity))
  .map((r) => `${r.Category} / ${r.Issue}: do ${clip(r.Do, 120)}; don't ${clip(r["Don't"], 100)}`);

const kb = { styles, fonts, products, patterns, ux };
const out = path.resolve(here, "../extension/design-kb.js");
fs.writeFileSync(out, `// Generated by tools/build-design-kb.mjs from UI UX Pro Max (MIT, Next Level Builder). Do not edit by hand.\nself.RemodelDesignKB = ${JSON.stringify(kb)};\n`);
console.log(`styles=${styles.length} fonts=${fonts.length} products=${products.length} patterns=${patterns.length} ux=${ux.length} → ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
